import test from 'node:test';
import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer } from '../src/server.js';
import { setup, processFactory } from './helpers/setup.js';
test('MCP client discovers tools, creates an agent and receives structured errors', async t => {
  const { cwd, manager: helper, track } = await setup(t);
  const { server, manager } = await createServer({ root: helper.storage.root + '-mcp', processFactory });
  track(manager);
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'test', version: '1' });
  t.after(async () => { await client.close(); await server.close(); });
  await server.connect(serverTransport); await client.connect(clientTransport);
  const tools = await client.listTools(); assert.equal(tools.tools.length, 27);
  assert.equal(tools.tools.find(tool => tool.name === 'get_quota').annotations.readOnlyHint, true);
  assert.equal(tools.tools.find(tool => tool.name === 'get_subagent_health').annotations.readOnlyHint, true);
  assert.equal(tools.tools.find(tool => tool.name === 'get_model_profiles').annotations.readOnlyHint, true);
  assert.ok(tools.tools.find(tool => tool.name === 'bind_session'));
  assert.ok(tools.tools.find(tool => tool.name === 'organize_agents'));
  assert.ok(tools.tools.find(tool => tool.name === 'consult'));
  assert.ok(tools.tools.find(tool => tool.name === 'council'));
  assert.ok(tools.tools.find(tool => tool.name === 'cross_review'));
  const result = await client.callTool({ name: 'spawn_agent', arguments: { cwd, prompt: 'hello', provider: 'fake', model: 'cheap', ownedPaths: ['src'], workspaceMode: 'shared' } });
  assert.equal(result.isError, undefined);
  const agentId = result.structuredContent.result.id;
  assert.ok(agentId);
  const busyOrg = await client.callTool({ name: 'organize_agents', arguments: { agentIds: [agentId], archived: true } });
  if (busyOrg.isError) assert.match(busyOrg.content[0].text, /不能归档/);
  for (let after = 0; ; ) {
    const w = await client.callTool({ name: 'wait_agent', arguments: { agentIds: [agentId], after: { [agentId]: after }, timeoutMs: 5000 } });
    const item = w.structuredContent.result.results[0];
    after = item.nextSequence;
    if (['completed', 'completed-verified', 'completed-unverified', 'failed', 'interrupted', 'closed'].includes(item.agent.status)) break;
  }
  const orgRes = await client.callTool({ name: 'organize_agents', arguments: { agentIds: [agentId], title: '保守复核记录', note: '核心方案对比', pinned: true, group: '专题复核', archived: true } });
  assert.equal(orgRes.isError, undefined);
  assert.equal(orgRes.structuredContent.result.updatedAgents[0].organization.title, '保守复核记录');
  assert.equal(orgRes.structuredContent.result.updatedAgents[0].organization.group, 'custom:专题复核');
  assert.equal(orgRes.structuredContent.result.updatedAgents[0].organization.archived, true);
  const activeOnly = await client.callTool({ name: 'list_agents', arguments: { includeSaved: true, archiveFilter: 'active' } });
  assert.equal(activeOnly.structuredContent.result.agents.length, 0);
  const archivedOnly = await client.callTool({ name: 'list_agents', arguments: { includeSaved: true, archiveFilter: 'archived' } });
  assert.equal(archivedOnly.structuredContent.result.agents[0].displayName, '保守复核记录');
  const rec = manager.storage.load(agentId);
  rec.updatedAt = new Date(Date.now() + 5000).toISOString();
  manager.storage.save(rec);
  const noteUpdate = await client.callTool({ name: 'organize_agents', arguments: { agentIds: [agentId], note: '已自动解除归档' } });
  assert.equal(noteUpdate.structuredContent.result.updatedAgents[0].organization.archived, false);
  const readRes = await client.callTool({ name: 'read_agent', arguments: { agentId } });
  assert.equal(readRes.structuredContent.result.organization.note, '已自动解除归档');
  assert.equal(readRes.structuredContent.result.organization.archived, false);
  const error = await client.callTool({ name: 'set_agent_model', arguments: { agentId, provider: 'fake', model: 'missing' } });
  assert.equal(error.isError, true); assert.match(error.content[0].text, /unavailable/);
});
